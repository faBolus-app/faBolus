import Foundation

/// Which category a pump notification belongs to, and what each surface does with a category: the phone
/// posts at the category's fixed level, and the watch follows the phone (R12). One function answers for
/// both surfaces, so the phone and the watch can't disagree about whether something alerts.
///
/// A surface intent is abstract, never a platform mechanism: iOS maps it to an interruption level, the
/// Garmin watch to `Toybox.Attention`.
public enum NotificationRules {

    /// A surface's intent for one notification, ordered `off < quiet < alert < urgent`. The v1 watch wire
    /// carries it as a token (`RemoteCommand.watchIntentWireToken`).
    public enum Intent: Int, Comparable, Sendable, Codable, CaseIterable {
        case off = 0, quiet = 1, alert = 2, urgent = 3
        public static func < (a: Intent, b: Intent) -> Bool { a.rawValue < b.rawValue }

        /// The intent a posted level expresses: time-sensitive and above break through Focus (urgent),
        /// active sounds (alert), passive doesn't (quiet).
        public init(level: AlertInterruptionLevel) {
            switch level {
            case .passive: self = .quiet
            case .active: self = .alert
            case .timeSensitive, .critical: self = .urgent
            }
        }
    }

    /// Whether a notification mirrors the pump's own annunciation or is generated by the app.
    public enum Source: String, Sendable, Codable, CaseIterable {
        case pumpMirror, appOwn
    }

    /// The phone's and the watch's intent for `category` under `policy`. The phone's comes from the
    /// broker's decision. The watch follows it, capped at `alert`: the Garmin ladder has no rung that
    /// breaks through, so a time-sensitive phone alert vibrates the watch, and a category that is off on
    /// the phone is off on the watch.
    public static func resolve(_ category: NotificationBroker.Category, policy: AlertPolicy) -> (
        phone: Intent, watch: Intent
    ) {
        let phone = NotificationBroker.decide(category, policy: policy).level.map(Intent.init(level:)) ?? .off
        return (phone, Swift.min(phone, .alert))
    }

    // MARK: - Pump notifications

    /// Alert bits pumpx2 names as CGM alerts (`AlertStatusResponse.AlertResponseType`): low transmitter
    /// (19), transmitter alert (20), sensor expiring (22), CGM graph removed (25), calibration (27, 28),
    /// invalid transmitter ID (29), transmitter end of life (39), CGM errors (40–42), transmitter expiring
    /// (44–46) and CGM unavailable (48). The firmware names of 19, 20 and 22 disagree with pumpx2's
    /// (UNVERIFIED-GUESSES #17); getting one wrong only moves it to the other switch, both on by default.
    static let cgmAlertBits: Set<Int> = [19, 20, 22, 25, 27, 28, 29, 39, 40, 41, 42, 44, 45, 46, 48]

    /// The category a pump notification is posted under, the same two switches Tandem's app has. A CGM
    /// alert, or an alert bit pumpx2 names as a CGM alert or error, is "CGM alerts & errors"; every alarm,
    /// malfunction, other alert and reminder is "Pump alerts & alarms". An alarm or malfunction is always
    /// the pump's, whatever its bit, because it stops delivery.
    public static func category(for alert: PumpAlert) -> NotificationBroker.Category {
        if alert.isMalfunction { return .pumpAlert }
        switch alert.kind {
        case .cgmAlert: return .pumpCgmAlert
        case .alert: return cgmAlertBits.contains(alert.id) ? .pumpCgmAlert : .pumpAlert
        case .alarm, .reminder: return .pumpAlert
        }
    }
}
